export function isEnemyUnlocked(enemy: EnemyCatalogEntry, highestUnlockedStage: number): boolean {
  return highestUnlockedStage >= enemy.unlockStage;
}

export function isAllyUnlocked(ally: AllyCatalogEntry, highestUnlockedStage: number): boolean {
  return highestUnlockedStage >= ally.unlockStage;
}

export function getUnlockedEnemiesForStage(stage: number): EnemyCatalogEntry[] {
  return ENEMY_ALBUM.filter((e) => e.unlockStage <= stage);
}

export function getUnlockedAlliesForStage(stage: number): AllyCatalogEntry[] {
  return ALLY_ALBUM.filter((a) => a.unlockStage <= stage);
}

export function getEnemyUnlockForStage(stage: number): EnemyCatalogEntry | undefined {
  return ENEMY_ALBUM.find((e) => e.unlockStage === stage);
}

export function getAllyUnlockForStage(stage: number): AllyCatalogEntry | undefined {
  return ALLY_ALBUM.find((a) => a.unlockStage === stage);
}
